// 記事 frontmatter の `faq` が配列なら正規化、無ければカテゴリ別デフォルトを返す。
export function getFaqForPost(post) {
  if (Array.isArray(post.faq) && post.faq.length > 0) {
    const normalized = post.faq
      .map((item) => {
        if (!item) return null;
        const q = (item.q || item.question || '').trim();
        const a = (item.a || item.answer || '').trim();
        if (!q || !a) return null;
        return { q, a };
      })
      .filter(Boolean);
    if (normalized.length > 0) return normalized;
  }
  return DEFAULT_FAQ_BY_CATEGORY[post.category] || DEFAULT_FAQ_BY_CATEGORY.powerstones;
}

export function faqJsonLd(faq) {
  return {
    '@context': 'https://schema.org',
    '@type': 'FAQPage',
    mainEntity: faq.map((item) => ({
      '@type': 'Question',
      name: item.q,
      acceptedAnswer: {
        '@type': 'Answer',
        text: item.a,
      },
    })),
  };
}
